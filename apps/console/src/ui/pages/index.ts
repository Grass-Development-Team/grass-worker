export interface RouteDefinition {
  pattern: string;
  tag: string;
  title: string;
  layout: "auth" | "console" | "create";
  access: "public" | "guest" | "user" | "admin" | "team-admin";
  load: () => Promise<unknown>;
}
function route(
  pattern: string,
  tag: string,
  title: string,
  load: () => Promise<unknown>,
  access: RouteDefinition["access"] = "user",
  layout: RouteDefinition["layout"] = "console",
): RouteDefinition {
  return { pattern, tag, title, load, access, layout };
}
